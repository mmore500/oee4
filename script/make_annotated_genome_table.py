#!/usr/bin/env python3
"""Flatten an annotated DISHTINY genome JSON into a CSV, one row per site.

The JSON that DISHTINY dumps for a specimen carries, for each instruction, its
operation name, its three raw argument bytes, its 64-bit tag, and a list of
human-readable ``descriptors`` generated by the operation's own
``descriptors()`` method.  This script lifts every descriptor key into its own
column so that the genome can be tabulated directly from a committed data file.

Module numbers are assigned by scanning for ``Global Anchor`` instructions,
each of which registers the tag that makes the following run of instructions
addressable; module ``n`` spans from the ``n``-th anchor up to, but excluding,
the next one.  ``Nop-0`` does not open a module: despite its name sharing a
prefix with the nop substituted by single-site knockouts, every ``Nop``
performs no operation.

One column is derived rather than copied: ``target_label`` joins a state
target with its index.  Every other column is copied verbatim out of the JSON.

Two outputs are written.  The CSV is RFC 4180, quoted where fields contain
commas, and is the file to analyse.  The ``.tex`` file holds the same rows as
``\\genomerow`` calls with TeX-special characters escaped, because instruction
semantics contain ``%``, ``&``, ``~``, ``^``, ``_`` and ``|``, which neither
csvsimple nor datatool reads safely out of a CSV; a LaTeX table therefore
\\input{}s the rows file rather than parsing the CSV itself.

Usage:
    ./make_annotated_genome_table.py <genome.json> <out.csv> <out.tex>
"""

import csv
import json
import sys

# descriptor keys this script knows how to place
KNOWN_DESCRIPTORS = [
    "summary",
    "argument a",
    "argument b",
    "argument c",
    "value",
    "probability",
    "target",
    "target index",
    "target jump table",
    "tag moniker",
    "tag bits",
]

COLUMNS = [
    "site",
    "module",
    "module_offset",
    "module_size",
    "operation",
    "summary",
    "arg_a",
    "arg_b",
    "arg_c",
    "value",
    "probability",
    "target",
    "target_index",
    "target_label",
    "target_jump_table",
    "tag_moniker",
    "tag_bits",
]

TEX_ESCAPES = {
    "\\": r"\textbackslash{}",
    "&": r"\&",
    "%": r"\%",
    "$": r"\$",
    "#": r"\#",
    "_": r"\_",
    "{": r"\{",
    "}": r"\}",
    "~": r"\textasciitilde{}",
    "^": r"\textasciicircum{}",
    "|": r"\textbar{}",
}


def tex_escape(text):
    return "".join(TEX_ESCAPES.get(char, char) for char in text)


def load_program(path):
    with open(path) as handle:
        return json.load(handle)["value0"]["program"]


def module_bounds(program):
    """Return one (module_index, module_start, module_end) triple per site."""
    anchors = [
        idx
        for idx, inst in enumerate(program)
        if inst["operation"] == "Global Anchor"
    ]

    out = []
    for site in range(len(program)):
        preceding = [anchor for anchor in anchors if anchor <= site]
        if not preceding:
            out.append((None, None, None))
            continue
        module = len(preceding) - 1
        start = anchors[module]
        end = anchors[module + 1] if module + 1 < len(anchors) else len(program)
        out.append((module, start, end))

    return out


def main():
    try:
        __, genome_path, csv_path, tex_path = sys.argv
    except ValueError:
        print(__doc__)
        sys.exit(1)

    program = load_program(genome_path)
    bounds = module_bounds(program)
    rows = []

    with open(csv_path, "w", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=COLUMNS)
        writer.writeheader()

        for site, inst in enumerate(program):
            descriptors = {
                entry["key"]: entry["value"] for entry in inst["descriptors"]
            }
            module, start, end = bounds[site]
            args = inst["args"]

            summary = descriptors.get("summary", "")
            target = descriptors.get("target", "").replace("dish2::", "")
            target_index = descriptors.get("target index", "")

            row = {
                "site": site,
                "module": "" if module is None else module,
                "module_offset": "" if start is None else site - start,
                "module_size": "" if start is None else end - start,
                "operation": inst["operation"],
                "summary": summary,
                "arg_a": args.get("value0", ""),
                "arg_b": args.get("value1", ""),
                "arg_c": args.get("value2", ""),
                "value": descriptors.get("value", ""),
                "probability": descriptors.get("probability", ""),
                "target": target,
                "target_index": target_index,
                "target_label": (
                    f"{target}[{target_index}]" if target else ""
                ),
                "target_jump_table": descriptors.get(
                    "target jump table", ""
                ),
                "tag_moniker": descriptors.get("tag moniker", ""),
                "tag_bits": descriptors.get("tag bits", ""),
            }
            writer.writerow(row)
            rows.append(row)

    # The columns a printed table needs, in the order \genomerow takes them.
    # The three register arguments are joined into one field because a LaTeX
    # macro takes at most nine parameters.
    def tex_row_fields(row):
        return [
            row["site"],
            row["module"],
            row["module_offset"],
            row["operation"],
            row["summary"],
            "{arg_a},{arg_b},{arg_c}".format(**row),
            row["target_label"],
            row["value"],
        ]

    with open(tex_path, "w") as handle:
        handle.write(
            "% Generated by script/make_annotated_genome_table.py "
            f"from {genome_path}.\n"
            "% Do not edit by hand.  One \\genomerow per genome site; see\n"
            "% table/annotated_genome.tex for the macro that typesets them.\n"
        )
        for row in rows:
            fields = "".join(
                "{" + tex_escape(str(field)) + "}"
                for field in tex_row_fields(row)
            )
            handle.write(f"\\genomerow{fields}\n")

    unplaced = {
        key
        for inst in program
        for key in (entry["key"] for entry in inst["descriptors"])
        if key not in KNOWN_DESCRIPTORS
    }
    if unplaced:
        print(f"warning: descriptor keys without a column: {sorted(unplaced)}")

    print(f"wrote {len(program)} sites to {csv_path} and {tex_path}")


if __name__ == "__main__":
    main()
